function generateTelemetryHistory(r24: number, sm: number, pw: number, tr: number, disp: number): SensorTelemetry[] {
  const history: SensorTelemetry[] = [];
  const hours = [24, 20, 16, 12, 8, 4, 2, 0];
  for (let i = 0; i < hours.length; i++) {
    const factor = (i + 1) / hours.length;
    history.push({
      timestamp: `${hours[i]}h ago`,
      rainfall1hMm: Number(((r24 / 12) * (0.6 + factor * 0.8)).toFixed(1)),
      rainfall24hMm: Number((r24 * (0.3 + factor * 0.7)).toFixed(1)),
      rainfall72hMm: Number((r24 * 2.2 * (0.4 + factor * 0.6)).toFixed(1)),
      soilMoistureVwcPct: Number((sm * (0.7 + factor * 0.3)).toFixed(1)),
      poreWaterPressureKPa: Number((pw * (0.6 + factor * 0.4)).toFixed(1)),
      tiltRateDegHr: Number((tr * (0.3 + factor * 0.7)).toFixed(2)),
      tiltAngleXDeg: Number((tr * 10 * (0.4 + factor * 0.6)).toFixed(2)),
      tiltAngleYDeg: Number((-tr * 5 * (0.4 + factor * 0.6)).toFixed(2)),
      tiltAngleZDeg: Number((tr * 1.5 * factor).toFixed(2)),
      cumulativeDisplacementMm: Number((disp * (0.5 + factor * 0.5)).toFixed(1)),
      vibrationRmsHz: Number((8 + factor * 6).toFixed(1)),
      ambientTempC: 21,
    });
  }
  return history;
}

